"""Writes forge-gui/res/forge-table/arena-brawl-pool.txt: every card on MTG Arena's 100-card Brawl card pool, one name a
line. Source: Scryfall's oracle-cards bulk file, cards whose "brawl" legality is legal or banned (Scryfall's
"brawl" is Arena's Brawl; a card banned in casual Brawl is still an Arena card, and Competitive Brawl's own bans are
applied by forge.bridge.Formats). No rebalanced "A-" cards: Arena reverted them all to their original printings on
2026-09-22 (State of the Formats 2026); digital-only Alchemy cards stay legal and are kept. Re-run when Arena adds a set:
  curl -s https://api.scryfall.com/bulk-data/oracle-cards   (take jsonl_download_uri), download it, then
  python3 -I arena-brawl-pool.py <oracle-cards.jsonl.gz> <out.txt>"""
import gzip, json, sys

names = set()
with gzip.open(sys.argv[1], 'rt', encoding='utf-8') as f:
    for line in f:
        card = json.loads(line)
        if card.get('legalities', {}).get('brawl') in ('legal', 'banned'):
            names.add(card['name'])
            for face in card.get('card_faces', []):
                names.add(face['name'])  # Forge names a transforming or modal card by its front face
src = sys.argv[1].rsplit('/', 1)[-1]
with open(sys.argv[2], 'w', encoding='utf-8') as out:
    out.write(f'# MTG Arena Brawl card pool from Scryfall ({src}); generated by forge-gui-bridge/deploy/arena-brawl-pool.py\n')
    out.writelines(n + '\n' for n in sorted(names))
print(len(names), 'names')
