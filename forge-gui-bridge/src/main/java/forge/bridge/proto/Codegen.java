package forge.bridge.proto;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import forge.bridge.proj.ViewCodec;
import forge.game.GameType;
import forge.game.phase.PhaseType;
import forge.game.zone.ZoneType;
import forge.trackable.TrackableProperty;

/**
 * Generates {@code forge-gui-web/protocol/src/generated/props.ts}: the JSON key and TypeScript type of every
 * {@link TrackableProperty} the bridge sends, and the engine enums the client switches on.
 * The output is committed; {@code ProtocolCodegenTest} fails when it is stale.
 *
 * Forge must be booted first (engine enums localize their names at class init).
 *
 * <p>Regenerate with {@code mvn -pl forge-gui-bridge test -Dtest=ProtocolCodegenTest -Dforge.codegen.write=true}.
 */
public final class Codegen {
    public static final String RELATIVE_PATH = "protocol/src/generated/props.ts";

    private Codegen() { }

    public static String generate() {
        final StringBuilder sb = new StringBuilder();
        sb.append("// GENERATED by forge.bridge.proto.Codegen from forge-game's TrackableProperty. Do not edit.\n");
        sb.append("// Regenerate: mvn -pl forge-gui-bridge test -Dtest=ProtocolCodegenTest -Dforge.codegen.write=true\n\n");
        sb.append("export interface CardType {\n  super: string[];\n  core: string[];\n  sub: string[];\n}\n\n");
        sb.append("export interface Keyword {\n  title: string;\n  reminder?: string;\n}\n\n");
        sb.append("/**\n * Every view property the bridge may send, keyed by its JSON name. Card, card-face, player and game\n");
        sb.append(" * objects each carry the subset that applies to them; default values (false, 0, \"\") are omitted.\n");
        sb.append(" * Card and player references are client ids (\"c12\", \"f3\", \"p1\").\n */\n");
        sb.append("export interface TrackableProps {\n");
        for (final TrackableProperty prop : TrackableProperty.values()) {
            if (!ViewCodec.isEncodable(prop) || ViewCodec.PLAYER_ZONES.contains(prop)) {
                continue;
            }
            sb.append("  ").append(ViewCodec.key(prop)).append("?: ").append(ViewCodec.tsType(prop)).append(";\n");
        }
        sb.append("}\n\n");
        sb.append("/** JSON keys of the player zone lists (under Player.zones). */\n");
        sb.append("export type ZoneKey =");
        boolean first = true;
        for (final TrackableProperty z : ViewCodec.PLAYER_ZONES) {
            sb.append(first ? " " : " | ").append('"').append(ViewCodec.key(z)).append('"');
            first = false;
        }
        sb.append(";\n\n");
        appendEnum(sb, "ZONE_TYPES", "ZoneType", List.of(ZoneType.values()));
        appendEnum(sb, "PHASE_TYPES", "PhaseType", List.of(PhaseType.values()));
        appendEnum(sb, "GAME_TYPES", "GameType", List.of(GameType.values()));
        return sb.toString();
    }

    private static void appendEnum(final StringBuilder sb, final String constName, final String typeName, final List<? extends Enum<?>> values) {
        sb.append("export const ").append(constName).append(" = [");
        for (int i = 0; i < values.size(); i++) {
            sb.append(i == 0 ? "" : ", ").append('"').append(values.get(i).name()).append('"');
        }
        sb.append("] as const;\n");
        sb.append("export type ").append(typeName).append(" = (typeof ").append(constName).append(")[number];\n\n");
    }

    public static void write(final Path webRoot) throws IOException {
        final Path out = webRoot.resolve(RELATIVE_PATH);
        Files.createDirectories(out.getParent());
        Files.writeString(out, generate(), StandardCharsets.UTF_8);
    }
}
